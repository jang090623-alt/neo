def height(texts_widths, base):
    """줄바꿈 칸의 줄 수로 행 높이 (한글은 2칸으로 셈)"""
    n = max(-(-sum(2 if ord(ch) > 0x2E80 else 1 for ch in str(t)) // int(w - 2)) for t, w in texts_widths)
    return max(base, 15.0 * n + 5)

