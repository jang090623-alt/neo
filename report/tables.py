def run_table(D):
    rows = [['윤활제'] + [f'{t}분' for t in T6]]
    for k in ('ATF', 'TOP', 'RAC', 'GEP'):
        t, T, lo, hi = D[k]; rows.append([NAME[k]] + [f'{T[i]:.1f} / {rng(lo[i], hi[i])}' for i in range(6)])
    return rows

def summary():
    rows = [['윤활제', '실험 2 회전수 평균 (범위, RPM)', '실험 2 온도 변화 (℃)', '실험 3 회전수 평균 (범위, RPM)', '실험 3 15분 뒤 온도 (℃)']]
    for k in ('ATF', 'TOP', 'RAC', 'GEP', 'GRS'):
        t, T, lo, hi = ROOM[k]; m = mid(lo, hi)
        r = [NAME[k], f'{sum(m)/len(m):.1f} ({min(lo)}~{max(hi)})', f'{T[-1]-T[0]:+.1f}' if T else '미측정']
        if k in HOT:
            t, T, lo, hi = HOT[k]; m = mid(lo, hi); r += [f'{sum(m)/len(m):.1f} ({min(lo)}~{max(hi)})', f'{T[-1]:.1f}']
        else: r += ['-', '-']
        rows.append(r)
    return rows

